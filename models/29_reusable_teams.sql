-- Optional reusable teams.
-- A team is reusable across tournaments; tournament entries snapshot the
-- members so historical results do not change when the team changes later.

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null,
  parent_team_id bigint references public.teams(id) on update cascade on delete set null,
  description text,
  is_active boolean not null default true,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name, parent_team_id)
);

create table if not exists public.team_members (
  team_id bigint not null references public.teams(id) on update cascade on delete cascade,
  employee_id text not null references public.employees(employee_code) on update cascade on delete restrict,
  role text not null default 'member',
  joined_at timestamptz not null default now(),
  primary key (team_id, employee_id)
);

-- A player can belong to only one reusable team at a time.
create unique index if not exists team_members_one_team_per_player_idx
  on public.team_members (employee_id);

create table if not exists public.tournament_team_entries (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on update cascade on delete cascade,
  team_id bigint not null references public.teams(id) on update cascade on delete restrict,
  seed integer,
  status text not null default 'registered'
    check (status in ('registered', 'active', 'eliminated', 'withdrawn')),
  created_at timestamptz not null default now(),
  unique (tournament_id, team_id)
);

create table if not exists public.tournament_team_member_snapshots (
  tournament_team_entry_id bigint not null references public.tournament_team_entries(id) on update cascade on delete cascade,
  employee_id text not null references public.employees(employee_code) on update cascade on delete restrict,
  role text not null default 'member',
  primary key (tournament_team_entry_id, employee_id)
);

create or replace function public.snapshot_tournament_team_members()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.tournament_team_member_snapshots
    (tournament_team_entry_id, employee_id, role)
  select new.id, tm.employee_id, tm.role
  from public.team_members tm
  where tm.team_id = new.team_id
  on conflict (tournament_team_entry_id, employee_id) do nothing;
  return new;
end;
$$;

drop trigger if exists snapshot_tournament_team_members_after_insert
  on public.tournament_team_entries;
create trigger snapshot_tournament_team_members_after_insert
after insert on public.tournament_team_entries
for each row execute function public.snapshot_tournament_team_members();

-- Cumulative points by reusable team, based on the member snapshot used in
-- each tournament. This does not replace the existing player leaderboard.
create or replace view public.team_cumulative_points as
select
  t.id as team_id,
  t.name as team_name,
  coalesce(sum(tp.points), 0)::integer as total_points,
  count(distinct tte.tournament_id)::integer as tournaments_played
from public.teams t
left join public.tournament_team_entries tte on tte.team_id = t.id
left join public.tournament_team_member_snapshots snapshot
  on snapshot.tournament_team_entry_id = tte.id
left join public.tournament_participants tp
  on tp.tournament_id = tte.tournament_id
 and tp.employee_id = snapshot.employee_id
group by t.id, t.name;

