-- Optional admin-awarded player points. These are separate from match scores.
create table if not exists public.player_point_awards (
  id bigint generated by default as identity primary key,
  tournament_id bigint references public.tournaments(id) on update cascade on delete cascade,
  employee_id text not null references public.employees(employee_code) on update cascade on delete restrict,
  team_id bigint references public.teams(id) on update cascade on delete restrict,
  points numeric(10,2) not null check (points > 0),
  reason text,
  created_by text,
  created_at timestamptz not null default now()
);

-- Also supports installations that already ran the first version of this
-- migration, where tournament_id was initially required.
alter table public.player_point_awards
  alter column tournament_id drop not null;

create index if not exists player_point_awards_tournament_idx on public.player_point_awards (tournament_id);
create index if not exists player_point_awards_employee_idx on public.player_point_awards (employee_id);
create index if not exists player_point_awards_team_idx on public.player_point_awards (team_id);

alter table public.player_point_awards enable row level security;
drop policy if exists player_point_awards_select_authenticated on public.player_point_awards;
create policy player_point_awards_select_authenticated on public.player_point_awards
  for select using ((select auth.role()) = 'authenticated');
drop policy if exists player_point_awards_admin_write on public.player_point_awards;
create policy player_point_awards_admin_write on public.player_point_awards
  for all using (public.app_is_admin()) with check (public.app_is_admin());

drop view if exists public.team_cumulative_points;
create or replace view public.team_cumulative_points as
with all_points as (
  select team_id, tournament_id, score as points
  from public.team_match_score_entries
  union all
  select team_id, tournament_id, points
  from public.player_point_awards
  where team_id is not null
)
select
  t.id as team_id,
  t.name as team_name,
  coalesce(sum(p.points), 0)::numeric(12,2) as total_points,
  count(distinct p.tournament_id)::integer as tournaments_played
from public.teams t
left join all_points p on p.team_id = t.id
where t.is_active = true
group by t.id, t.name;
