-- Multi-team games for reusable-team tournaments.
-- A single match can contain any number of registered reusable teams.
create table if not exists public.tournament_match_teams (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.tournament_matches(id) on update cascade on delete cascade,
  team_id bigint not null references public.teams(id) on update cascade on delete restrict,
  position integer not null default 1,
  score integer not null default 0 check (score >= 0),
  is_winner boolean not null default false,
  created_at timestamptz not null default now(),
  unique (match_id, team_id),
  unique (match_id, position)
);

create index if not exists tournament_match_teams_match_idx on public.tournament_match_teams(match_id);
create index if not exists tournament_match_teams_team_idx on public.tournament_match_teams(team_id);

alter table public.tournament_match_teams enable row level security;
drop policy if exists tournament_match_teams_select_authenticated on public.tournament_match_teams;
create policy tournament_match_teams_select_authenticated on public.tournament_match_teams
  for select using ((select auth.role()) = 'authenticated');
drop policy if exists tournament_match_teams_admin_write on public.tournament_match_teams;
create policy tournament_match_teams_admin_write on public.tournament_match_teams
  for all using (public.app_is_admin()) with check (public.app_is_admin());
