-- Tournament Teams table
-- Decouples participants from matches to support flexible team sizes (1v1, 5v5, 11v11, etc.)
create table if not exists public.tournament_teams (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on update cascade on delete cascade,
  team_name text,
  members jsonb not null default '[]'::jsonb, -- Array of employee codes: ["EMP001", "EMP002", ...]
  captain_id text references public.employees(employee_code) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(members) = 'array')
);

create index if not exists tournament_teams_tournament_idx on public.tournament_teams (tournament_id);
create index if not exists tournament_teams_captain_idx on public.tournament_teams (captain_id);

drop trigger if exists set_tournament_teams_updated_at on public.tournament_teams;
create trigger set_tournament_teams_updated_at
before update on public.tournament_teams
for each row execute function public.touch_updated_at();
