-- Final results table
-- One row per (tournament, employee) that finished in a paying / podium
-- position. `position` follows standard tournament order: 1 (champion),
-- 2 (runner-up), 3 (3rd place), 4+ (participation).
-- For round-robin / league events you may also store the full standings here
-- instead of using position-based semantics.

create table if not exists public.final_results (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on update cascade on delete cascade,
  employee_id text not null references public.employees(employee_code) on update cascade on delete restrict,
  department text,
  position integer not null,
  matches_played integer not null default 0,
  wins integer not null default 0,
  losses integer not null default 0,
  points integer not null default 0,
  prize_amount numeric(10,2),
  prize_description text,
  certificate_issued boolean not null default false,
  declared_by text,
  declared_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tournament_id, employee_id),
  check (position >= 1)
);

create index if not exists final_results_tournament_idx on public.final_results (tournament_id);
create index if not exists final_results_employee_idx on public.final_results (employee_id);
create index if not exists final_results_position_idx on public.final_results (position);

alter table if exists public.final_results
  add column if not exists department text;

alter table if exists public.final_results
  add column if not exists prize_amount numeric(10,2);

alter table if exists public.final_results
  add column if not exists prize_description text;

alter table if exists public.final_results
  add column if not exists certificate_issued boolean not null default false;

alter table if exists public.final_results
  add column if not exists declared_by text;

alter table if exists public.final_results
  add column if not exists updated_at timestamptz not null default now();

drop trigger if exists set_final_results_updated_at on public.final_results;
create trigger set_final_results_updated_at
before update on public.final_results
for each row execute function public.touch_updated_at();
