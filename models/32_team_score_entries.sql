-- Score-based reusable team totals.
-- One row is stored for every player in every completed/recorded match.
-- If two players share a team, both rows count toward that team's total.

create table if not exists public.team_match_score_entries (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams(id) on update cascade on delete restrict,
  tournament_id bigint not null references public.tournaments(id) on update cascade on delete cascade,
  match_id bigint not null references public.tournament_matches(id) on update cascade on delete cascade,
  employee_id text not null references public.employees(employee_code) on update cascade on delete restrict,
  side text not null check (side in ('A', 'B')),
  score integer not null default 0 check (score >= 0),
  created_at timestamptz not null default now(),
  unique (match_id, employee_id, side)
);

create index if not exists team_match_score_entries_team_idx
  on public.team_match_score_entries (team_id);

create index if not exists team_match_score_entries_employee_idx
  on public.team_match_score_entries (employee_id);

create or replace view public.team_cumulative_points as
select
  t.id as team_id,
  t.name as team_name,
  coalesce(sum(s.score), 0)::integer as total_points,
  count(distinct s.tournament_id)::integer as tournaments_played
from public.teams t
left join public.team_match_score_entries s on s.team_id = t.id
where t.is_active = true
group by t.id, t.name;

alter table public.team_match_score_entries enable row level security;

drop policy if exists team_match_score_entries_select_authenticated
  on public.team_match_score_entries;
create policy team_match_score_entries_select_authenticated
  on public.team_match_score_entries for select
  using ((select auth.role()) = 'authenticated');

drop policy if exists team_match_score_entries_insert_authenticated
  on public.team_match_score_entries;
create policy team_match_score_entries_insert_authenticated
  on public.team_match_score_entries for insert
  with check ((select auth.role()) = 'authenticated');

drop policy if exists team_match_score_entries_update_authenticated
  on public.team_match_score_entries;
create policy team_match_score_entries_update_authenticated
  on public.team_match_score_entries for update
  using ((select auth.role()) = 'authenticated')
  with check ((select auth.role()) = 'authenticated');

drop policy if exists team_match_score_entries_delete_authenticated
  on public.team_match_score_entries;
create policy team_match_score_entries_delete_authenticated
  on public.team_match_score_entries for delete
  using ((select auth.role()) = 'authenticated');
