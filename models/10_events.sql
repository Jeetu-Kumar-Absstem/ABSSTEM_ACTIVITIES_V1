drop trigger if exists set_events_updated_at on public.events;
create trigger set_events_updated_at
before update on public.events
for each row execute function public.touch_updated_at();

-- Auto-stamp event_status from the date when it isn't manually set.
create or replace function public.events_sync_status()
returns trigger
language plpgsql
as $$
begin
  if new.event_status is null
     or new.event_status in ('scheduled', 'ongoing', 'completed')
  then
    if new.end_date is not null and new.end_date < current_date then
      new.event_status := 'completed';
    elsif new.start_date < current_date
          and (new.end_date is null or new.end_date >= current_date)
    then
      new.event_status := 'ongoing';
    elsif new.start_date >= current_date then
      new.event_status := 'scheduled';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists events_sync_status_trigger on public.events;
create trigger events_sync_status_trigger
before insert or update on public.events
for each row execute function public.events_sync_status();
