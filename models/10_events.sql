-- Events table
-- Stores both upcoming and past company / outstation / celebration / tournament events.
-- Status is derived from the event date; `event_status` lets admins override
-- (e.g. mark a future event as "completed" once it wraps up, or push a past
-- event to "cancelled").

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  description text,
  event_type text not null default 'company',
  start_date date not null,
  end_date date,
  start_time time,
  end_time time,
  venue text,
  location text,
  organizer text,
  max_participants integer,
  banner_color text,
  icon text,
  created_by text,
  is_published boolean not null default true,
  event_status text not null default 'scheduled',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (event_type in ('company', 'tournament', 'outstation', 'celebration')),
  check (event_status in ('scheduled', 'ongoing', 'completed', 'cancelled', 'postponed')),
  check (end_date is null or end_date >= start_date)
);

create index if not exists events_start_date_idx on public.events (start_date);
create index if not exists events_event_type_idx on public.events (event_type);
create index if not exists events_event_status_idx on public.events (event_status);

